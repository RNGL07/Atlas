def seed(conn):
    conn.executemany("INSERT INTO lines VALUES (?,?,?)", LINES)
    conn.executemany("INSERT INTO stations VALUES (?,?,?,?)", STATIONS)
    conn.executemany(
        "INSERT INTO addresses (address, station_code, addr_type, description) VALUES (?,?,?,?)",
        ADDRESSES,
    )
    conn.executemany(
        "INSERT INTO relationships (from_address, to_address, rel_type, condition_expr, description) VALUES (?,?,?,?,?)",
        RELATIONSHIPS,
    )
    conn.executemany("INSERT INTO fault_codes VALUES (?,?,?,?)", FAULT_CODES)
    conn.executemany("INSERT INTO fault_addresses VALUES (?,?,?)", FAULT_ADDRESSES)
    conn.executemany(
        "INSERT INTO live_state (address, value) VALUES (?,?)",
        list(NORMAL_STATE.items()),
    )
    conn.commit()


